    /// <summary>네 종류 전체 키의 빈 값(문자 '', 체크 false, 객체 {}) — 기존 BLANK 합집합</summary>
    private static JsonObject CeBlank()
    {
        var o = new JsonObject();
        foreach (var t in CeTypes)
            foreach (var f in CeSections(t).SelectMany(s => s.Fields))
            {
                if (f.Key == CeTypeKey) continue;
                switch (f.Kind)
                {
                    case DocFieldKind.Flags: foreach (var k in f.Keys) o[k] = false; break;
                    case DocFieldKind.Obj: o[f.Key] = new JsonObject(); break;
                    default: o[f.Key] = ""; break;
                }
            }
        return o;
    }

