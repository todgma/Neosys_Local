// ── DB 서식 오버라이드(캐시) ──
//  서버 cn_contract_template 의 body_json 을 category / tpl_code 로 조회.
//  body_json 은 데이터(intro/objective/clauses 등)만 담고 summary(함수)는 없음 → 코드 CATEGORY 위에 병합해 함수 보존.
let CATEGORY_OVERRIDES = {}; // category → body_json(obj)
let TPL_OVERRIDES = {};      // tpl_code → body_json(obj)

// 캐시 스토어에서 서버 템플릿 목록을 주입 (앱 실행 시 1회, 관리자 저장 후 갱신)
export function applyContractTemplateCache(items) {
  const cat = {}, tpl = {};
  for (const it of (items || [])) {
    let body = it.bodyJson ?? it.BodyJson ?? it.body_json;
    if (typeof body === 'string') { try { body = JSON.parse(body); } catch { body = null; } }
    if (!body) continue;
    const code = it.tplCode ?? it.TplCode ?? it.tpl_code;
    const category = it.category ?? it.Category;
    if (code) tpl[code] = body;
    // category 대표값: REAL_* 우선, 없으면 첫 항목
    if (category && (!cat[category] || String(code || '').startsWith('REAL'))) cat[category] = body;
  }
  CATEGORY_OVERRIDES = cat;
  TPL_OVERRIDES = tpl;
}

// docType(라벨) → 템플릿 구성. categoryOverride가 있으면 그 카테고리 우선. tplCode가 있으면 그 서식 우선(관리자 편집분).
export function buildContractTemplate(docLabel, categoryOverride, tplCode) {
  const doc = CONTRACT_DOCS.find((d) => d.label === docLabel);
  const category = categoryOverride || doc?.category || 'sale';
  const base = CATEGORY[category] || CATEGORY.sale;
  // DB 오버라이드(있으면 데이터 필드를 덮되 summary 등 코드 함수는 유지)
  const dbBody = (tplCode && TPL_OVERRIDES[tplCode]) || CATEGORY_OVERRIDES[category] || null;
  const cat = dbBody ? { ...base, ...dbBody } : base;
  const sign = SIGN_CONFIG[category] || SIGN_CONFIG.sale;
  return { ...cat, sign, docType: docLabel || (doc ? doc.label : CONTRACT_DOCS[0].label), category, ptTypeLabel: doc?.ptTypeLabel || '' };
}

// 템플릿에서 "간단 입력폼"이 채워야 할 항목(키)들을 그룹별로 추출
//  → 폼에서 입력한 값(doc)을 그대로 ContractDocumentEditor(미리보기)에 전달하면 자동 반영
export function extractContractFields(docLabel) {
  const tpl = buildContractTemplate(docLabel);
  const sign = tpl.sign || SIGN_CONFIG.sale;
  const seen = new Set();
  const collect = (arr, parts) => {
    (parts || []).forEach((p) => {
      if (p && typeof p === 'object' && p.k && !seen.has(p.k)) { seen.add(p.k); arr.push({ k: p.k, label: p.k }); }
    });
  };
  // 계약내용(금액/일자) — amountRows + 조항 내 입력필드
  const amounts = [];
  (tpl.amountRows || []).forEach((row) => collect(amounts, row.text));
  (tpl.clauses || []).forEach((c) => { if (Array.isArray(c)) collect(amounts, c); });
  // 부동산 표시
  const property = [
    { k: '소재지', label: '소재지', full: true },
    { k: '토지지목', label: '토지 지목' },
    { k: '토지면적', label: '토지 면적(㎡)' },
    { k: '건물구조', label: '건물 구조' },
    { k: '건물용도', label: '건물 용도' },
    { k: '건물면적', label: '건물 면적(㎡)' },
  ];
  // 당사자
  const parties = (sign.parties || []).map((p) => {
    const fields = [
      { k: `${p.role}_성명`, label: '성명' },
      { k: `${p.role}_주민번호`, label: sign.broker === 'gaeup' ? '주민번호' : '주민등록번호' },
      { k: `${p.role}_전화`, label: '전화' },
      { k: `${p.role}_주소`, label: '주소', full: true },
    ];
    if (sign.daeri === 'full') {
      fields.push({ k: `${p.role}_대리인성명`, label: '대리인 성명' }, { k: `${p.role}_대리인주민번호`, label: '대리인 주민번호' }, { k: `${p.role}_대리인주소`, label: '대리인 주소', full: true });
    } else if (sign.daeri === 'addrName') {
      fields.push({ k: `${p.role}_대리인성명`, label: '대리인 성명' }, { k: `${p.role}_대리인주소`, label: '대리인 주소', full: true });
    }
    return { role: p.role, label: String(p.label || p.role).replace(/\s+/g, ''), fields };
  });
  // 중개사
  const brokers = [];
  const bn = sign.broker === 'none' ? 0 : (sign.brokerCount || 1);
  for (let bi = 0; bi < bn; bi++) {
    const pf = bi === 0 ? '중개' : `중개${bi + 1}`;
    if (sign.broker === 'gaeup') {
      brokers.push({ label: `개업공인중개사${bn > 1 ? bi + 1 : ''}`, fields: [
        { k: `${pf}상호`, label: '상호' }, { k: `${pf}사무소소재지`, label: '사무소 소재지', full: true },
        { k: `${pf}등록번호`, label: '등록번호' }, { k: `${pf}대표`, label: '대표' },
        { k: `${pf}전화`, label: '전화' }, { k: `${pf}소속`, label: '소속' },
      ] });
    } else if (sign.broker === 'std') {
      brokers.push({ label: `공인중개사${bn > 1 ? (bi === 0 ? '①' : '②') : ''}`, fields: [
        { k: `${pf}사무소소재지`, label: '사무소 소재지', full: true }, { k: `${pf}등록번호`, label: '등록번호' },
        { k: `${pf}사무소명칭`, label: '사무소 명칭' }, { k: `${pf}전화`, label: '전화' }, { k: `${pf}대표`, label: '대표자 성명' },
      ] });
    } else if (sign.broker === 'exclusive') {
      brokers.push({ label: '중개업자(乙)', fields: [
        { k: '중개사무소소재지', label: '사무소 소재지', full: true }, { k: '중개등록번호', label: '등록번호' },
        { k: '중개상호', label: '상호' }, { k: '중개전화', label: '전화' }, { k: '중개대표', label: '성명' },
      ] });
    }
  }
  const etc = [
    { k: '특약사항', label: '특약사항', textarea: true, full: true },
    { k: '계약일자', label: '계약일자' },
  ];
  return { docType: tpl.docType, property, amounts, parties, brokers, etc };
}
